"""Independent synthetic tests of paired iid and moving-block bootstrap."""
import math
import random
import unittest

from paired_bootstrap import block_sensitivity, paired_bootstrap


class PairedBootstrapTests(unittest.TestCase):
    def test_identical_losses_give_exact_zero(self):
        losses = [i / 100 for i in range(40)]
        for method, block in (('iid', None), ('moving_block', 5)):
            with self.subTest(method=method):
                r = paired_bootstrap(losses, losses, method=method, block_length=block, replicates=200)
                self.assertEqual(r['mean_difference'], 0.0)
                self.assertEqual(r['interval'], [0.0, 0.0])

    def test_known_constant_paired_difference(self):
        result = paired_bootstrap([1.0] * 50, [3.0] * 50, method='moving_block', block_length=5, replicates=200)
        self.assertEqual(result['mean_difference'], -2.0)
        self.assertEqual(result['interval'], [-2.0, -2.0])

    def test_reference_percentiles_and_sampling(self):
        # Independently generated by drawing the specified index sequences,
        # summing samples directly, sorting, and interpolating (B-1)*p.
        a, b = list(range(20)), [0] * 20
        iid = paired_bootstrap(a, b, method='iid', replicates=100, seed=73)
        block = paired_bootstrap(a, b, method='moving_block', block_length=4,
                                 replicates=100, seed=73)
        self.assertAlmostEqual(iid['interval'][0], 6.41625)
        self.assertAlmostEqual(iid['interval'][1], 11.95)
        self.assertAlmostEqual(block['interval'][0], 5.795)
        self.assertAlmostEqual(block['interval'][1], 13.9)

    def test_reproducible_and_paired(self):
        a = [1.0 + (i % 7) for i in range(50)]
        b = [x + .5 for x in a]
        for method, block in (('iid', None), ('moving_block', 4)):
            kwargs = dict(method=method, block_length=block, replicates=200, seed=123)
            first = paired_bootstrap(a, b, **kwargs)
            self.assertEqual(first, paired_bootstrap(a, b, **kwargs))
            self.assertEqual(first['interval'], [-.5, -.5])

    def test_seed_and_length_sensitivity(self):
        rng = random.Random(20261113)
        a = [1.0 + rng.random() for _ in range(100)]
        b = [1.0 + rng.random() for _ in range(100)]
        x = paired_bootstrap(a, b, replicates=300, seed=1)
        y = paired_bootstrap(a, b, replicates=300, seed=2)
        self.assertNotEqual(x['interval'], y['interval'])
        values = block_sensitivity(iter(a), iter(b), [1, 5, 10], replicates=300)
        self.assertEqual([item['block_length'] for item in values], [1, 5, 10])
        self.assertEqual(len({item['mean_difference'] for item in values}), 1)

    def test_autocorrelated_series_block_interval_changes(self):
        # Independent fixed synthetic DGP: positive serial dependence is high.
        rng = random.Random(712)
        x, differences = 0.0, []
        for _ in range(160):
            x = .92 * x + rng.uniform(-.2, .2)
            differences.append(x)
        a = [2 + d for d in differences]
        b = [2] * len(a)
        iid = paired_bootstrap(a, b, replicates=500, seed=10)
        block = paired_bootstrap(a, b, method='moving_block', block_length=10, replicates=500, seed=10)
        width = lambda r: r['interval'][1] - r['interval'][0]
        self.assertGreater(width(block), width(iid))

    def test_reject_insufficient_and_nonfinite(self):
        with self.assertRaises(ValueError):
            paired_bootstrap([0] * 19, [0] * 19)
        with self.assertRaises(ValueError):
            paired_bootstrap([0] * 20, [0] * 21)
        for bad in (math.nan, math.inf, True, -1, '1'):
            with self.subTest(bad=repr(bad)), self.assertRaises(ValueError):
                paired_bootstrap([bad] + [0] * 19, [0] * 20)

    def test_reject_bad_configuration(self):
        a = [1.0] * 20
        for opts in ({'method':'bad'}, {'replicates':99}, {'seed': True}, {'confidence':1.0},
                     {'method':'iid', 'block_length':1},
                     {'method':'moving_block', 'block_length':5},
                     {'method':'moving_block', 'block_length':0}):
            with self.subTest(opts=opts), self.assertRaises(ValueError):
                paired_bootstrap(a, a, **opts)
        with self.assertRaises(ValueError):
            block_sensitivity(a, a, [2, 2], replicates=100)
        with self.assertRaises(ValueError):
            block_sensitivity(a, a, [[2]], replicates=100)


if __name__ == '__main__':
    unittest.main(verbosity=2)
